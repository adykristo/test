create or replace function public.admin_update_order(p_id uuid,p_status text)
returns void language plpgsql security definer set search_path = ''
as $$
declare v_order public.member_orders; v_days int; v_base timestamptz;
begin
  if not public.is_member_super_admin() then raise exception 'Hanya Admin Utama'; end if;
  if p_status not in ('pending','paid','failed','expired','refunded','cancelled') then raise exception 'Status tidak valid'; end if;
  select * into v_order from public.member_orders where id=p_id for update;
  if not found then raise exception 'Order tidak ditemukan'; end if;
  if v_order.status='refunded' then raise exception 'Order refund tidak dapat diubah'; end if;
  if v_order.status='paid' and p_status not in ('paid','refunded') then raise exception 'Order dibayar hanya dapat di-refund'; end if;
  update public.member_orders set status=p_status,paid_at=case when p_status='paid' then coalesce(paid_at,now()) else paid_at end where id=p_id;
  if p_status='paid' and v_order.status<>'paid' then
    select durasi_hari into v_days from public.member_packages where nama=v_order.paket;
    select case when status='aktif' and berakhir>now() then berakhir else now() end into v_base from public.member_profiles where id=v_order.user_id for update;
    update public.member_profiles set status='aktif',paket=v_order.paket,berakhir=v_base+make_interval(days=>coalesce(v_days,30)) where id=v_order.user_id;
  end if;
  insert into public.member_admin_logs(admin_id,aksi,target_type,target_id,detail)
  values(auth.uid(),'ubah_status_transaksi','order',p_id::text,jsonb_build_object('dari',v_order.status,'ke',p_status));
end; $$;

create or replace function public.admin_update_member(p_id uuid,p_action text,p_package text default '',p_note text default '')
returns void language plpgsql security definer set search_path = ''
as $$
declare v_profile public.member_profiles; v_days int; v_base timestamptz;
begin
  if not public.is_member_super_admin() then raise exception 'Hanya Admin Utama'; end if;
  if p_action not in ('activate','reject','reactivate','deactivate','soft_delete') then raise exception 'Aksi tidak valid'; end if;
  select * into v_profile from public.member_profiles where id=p_id for update;
  if not found then raise exception 'Member tidak ditemukan'; end if;
  if p_action='activate' then
    select durasi_hari into v_days from public.member_packages where nama=trim(p_package) and aktif=true;
    if v_days is null then raise exception 'Paket tidak valid'; end if;
    v_base:=case when v_profile.status='aktif' and v_profile.berakhir>now() then v_profile.berakhir else now() end;
    update public.member_profiles set status='aktif',paket=trim(p_package),berakhir=v_base+make_interval(days=>v_days),catatan_admin=left(trim(coalesce(p_note,'')),1000) where id=p_id;
  elsif p_action='reject' then
    update public.member_profiles set status='ditolak',catatan_admin=left(trim(coalesce(p_note,'')),1000) where id=p_id;
  elsif p_action='reactivate' then
    select durasi_hari into v_days from public.member_packages where nama=v_profile.paket;
    update public.member_profiles set status='aktif',berakhir=case when v_profile.berakhir>now() then v_profile.berakhir else now()+make_interval(days=>coalesce(v_days,30)) end where id=p_id;
  elsif p_action='deactivate' then
    update public.member_profiles set status='nonaktif',catatan_admin=left(trim(coalesce(p_note,'')),1000) where id=p_id;
  else
    update public.member_profiles set status='dihapus',catatan_admin=left(trim(coalesce(p_note,'')),1000) where id=p_id;
  end if;
  insert into public.member_admin_logs(admin_id,aksi,target_type,target_id,detail)
  values(auth.uid(),'member_'||p_action,'member',p_id::text,jsonb_build_object('paket',p_package,'status_sebelum',v_profile.status,'alasan',left(trim(coalesce(p_note,'')),1000)));
end; $$;

create or replace function public.process_payment_webhook(
  p_event_id text,p_order_id uuid,p_provider text,p_payment_id text,
  p_amount bigint,p_status text,p_payload jsonb
)
returns text language plpgsql security definer set search_path = ''
as $$
declare v_order public.member_orders; v_days int; v_base timestamptz;
begin
  if p_provider not in ('midtrans','xendit') or p_status not in ('pending','paid','failed','expired','refunded') then raise exception 'Payload pembayaran tidak valid'; end if;
  if char_length(coalesce(p_event_id,''))<3 or char_length(p_event_id)>200 then raise exception 'Event ID tidak valid'; end if;
  if exists(select 1 from public.member_webhook_events where id=p_provider||':'||p_event_id) then return 'duplicate'; end if;
  select * into v_order from public.member_orders where id=p_order_id for update;
  if not found then raise exception 'Order tidak ditemukan'; end if;
  if v_order.payment_provider<>p_provider or v_order.jumlah<>p_amount then raise exception 'Provider atau nominal tidak cocok'; end if;
  if v_order.payment_id is not null and p_payment_id<>'' and v_order.payment_id<>p_payment_id then raise exception 'Payment ID tidak cocok'; end if;
  insert into public.member_webhook_events(id,provider,order_id,payload) values(p_provider||':'||p_event_id,p_provider,p_order_id,coalesce(p_payload,'{}'));
  if v_order.status in ('refunded','cancelled') then return 'ignored'; end if;
  if v_order.status='paid' and p_status<>'refunded' then return 'already_paid'; end if;
  update public.member_orders set status=p_status,paid_at=case when p_status='paid' then now() else paid_at end,
    payment_id=coalesce(nullif(p_payment_id,''),payment_id),metadata=coalesce(p_payload,'{}') where id=p_order_id;
  if p_status='paid' then
    select durasi_hari into v_days from public.member_packages where nama=v_order.paket;
    select case when status='aktif' and berakhir>now() then berakhir else now() end into v_base from public.member_profiles where id=v_order.user_id for update;
    update public.member_profiles set status='aktif',paket=v_order.paket,berakhir=v_base+make_interval(days=>coalesce(v_days,30)) where id=v_order.user_id;
  end if;
  return 'processed';
end; $$;

create or replace function public.create_member_order(p_paket text,p_provider text default 'manual')
returns uuid language plpgsql security definer set search_path = ''
as $$
declare v_id uuid; v_price bigint; v_provider text;
begin
  if auth.uid() is null then raise exception 'Harus login'; end if;
  v_provider:=lower(trim(coalesce(p_provider,'manual')));
  if v_provider not in ('manual','midtrans','xendit') then raise exception 'Provider tidak valid'; end if;
  if (select count(*) from public.member_orders where user_id=auth.uid() and created_at>now()-interval '1 day')>=5 then raise exception 'Batas lima pesanan per hari tercapai'; end if;
  select harga into v_price from public.member_packages where nama=trim(p_paket) and aktif=true;
  if v_price is null then raise exception 'Paket tidak tersedia'; end if;
  select id into v_id from public.member_orders where user_id=auth.uid() and paket=trim(p_paket) and payment_provider=v_provider and status='pending' order by created_at desc limit 1;
  if v_id is not null then return v_id; end if;
  insert into public.member_orders(user_id,paket,jumlah,status,payment_provider)
  values(auth.uid(),trim(p_paket),v_price,'pending',v_provider) returning id into v_id;
  return v_id;
end; $$;

