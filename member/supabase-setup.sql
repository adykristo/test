-- Membuat order dengan harga dari database, bukan dari nilai yang dikirim browser.
-- Edge Function pembayaran dapat memakai id hasil fungsi ini untuk membuat transaksi
-- Midtrans/Xendit, lalu webhook tervalidasi mengubah status menjadi paid.
create or replace function public.create_member_order(p_paket text,p_provider text default 'manual')
returns uuid language plpgsql security definer set search_path = ''
as $$
declare v_id uuid; v_harga bigint;
begin
  if auth.uid() is null then raise exception 'Harus login'; end if;
  select harga into v_harga from public.member_packages where nama=p_paket and aktif=true;
  if v_harga is null then raise exception 'Paket tidak tersedia'; end if;
  insert into public.member_orders(user_id,paket,jumlah,payment_provider)
  values(auth.uid(),p_paket,v_harga,coalesce(nullif(trim(p_provider),''),'manual')) returning id into v_id;
  return v_id;
end; $$;

