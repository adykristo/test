create or replace function public.validate_member_content()
returns trigger language plpgsql set search_path = '' as $$
declare v_status text; v_count int;
begin
  if char_length(trim(new.topik))>160 or char_length(trim(new.judul))>240 then raise exception 'Judul atau topik terlalu panjang'; end if;
  if pg_column_size(new.data)>2500000 then raise exception 'Ukuran konten terlalu besar'; end if;
  if new.jenis not in ('soal','pdf','video','tryout','modul') then raise exception 'Jenis konten tidak valid'; end if;
  v_status:=coalesce(new.data->>'publication_status',case when new.visible then 'published' else 'draft' end);
  if v_status not in ('draft','review','scheduled','published','archived') then raise exception 'Status publikasi tidak valid'; end if;
  if new.jenis='soal' then
    v_count:=coalesce((new.data->>'package_question_count')::int,1);
    if v_count<1 or v_count>100 then raise exception 'Jumlah soal per paket harus 1 sampai 100'; end if;
  end if;
  new.data:=jsonb_set(new.data,'{publication_status}',to_jsonb(v_status),true);
  new.visible:=v_status='published';
  if v_status='archived' then new.archived_at:=coalesce(new.archived_at,now()); else new.archived_at:=null; end if;
  return new;
exception when invalid_text_representation then raise exception 'Jumlah soal tidak valid';
end; $$;
drop trigger if exists validate_member_content_trigger on public.member_content;
create trigger validate_member_content_trigger before insert or update on public.member_content
for each row execute function public.validate_member_content();

create or replace function public.version_member_content()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_next int; v_snapshot jsonb; v_content_id uuid;
begin
  if tg_op='DELETE' then v_snapshot:=to_jsonb(old);v_content_id:=old.id;else v_snapshot:=to_jsonb(new);v_content_id:=new.id;end if;
  select coalesce(max(version_no),0)+1 into v_next from public.member_content_versions
  where content_id=v_content_id;
  insert into public.member_content_versions(content_id,version_no,snapshot,changed_by,change_reason)
  values(v_content_id,v_next,v_snapshot,auth.uid(),case when tg_op='INSERT' then 'dibuat' when tg_op='DELETE' then 'dihapus' else 'diubah' end);
  if tg_op='DELETE' then return old;else return new;end if;
end; $$;
drop trigger if exists version_member_content_trigger on public.member_content;
create trigger version_member_content_trigger after insert or update or delete on public.member_content
for each row execute function public.version_member_content();

